%% setup_battery_component.m — rebuilds the missing battery component
pkg = fullfile(pwd, '+P45B_98S30P_Library', '+Modules');
if ~isfolder(pkg), mkdir(pkg); end

L = [
    "component ModuleType1";
    "% Lumped 7S30P module of Molicel INR-21700-P45B cells (rebuilt equivalent).";
    "% Parameter values (OCV/R0 tables, capacity, P, S) are stored in the model.";
    "    nodes";
    "        p = foundation.electrical.electrical; % +";
    "        n = foundation.electrical.electrical; % -";
    "    end";
    "    outputs";
    "        socOutCell = {1, '1'}; % SOC";
    "    end";
    "    annotations";
    "        p : Side = top;";
    "        n : Side = bottom;";
    "        socOutCell : Side = right;";
    "    end";
    "    parameters";
    "        SOC_vecCell = {[0 0.5 1], '1'};                                  % Vector of state-of-charge values";
    "        T_vecCell   = {[0 23 45], 'degC'};                               % Vector of temperatures";
    "        V0_matCell  = {[3.2 3.2 3.2; 3.7 3.7 3.7; 4.17 4.17 4.17], 'V'}; % Open-circuit voltage table";
    "        V_rangeCell = {[2.25 Inf], 'V'};                                 % Terminal voltage operating range";
    "        R0_matCell  = {0.01*ones(3,3), 'Ohm'};                           % Terminal resistance table";
    "        AHCell      = {4.493, 'A*hr'};                                   % Cell capacity";
    "        extrapolation_optionCell = simscape.enum.extrapolation.nearest; % Extrapolation method";
    "        thermal_massCell = {63, 'J/K'};                                  % Cell thermal mass";
    "        P = 30;                                                          % Number of cells in parallel";
    "        S = 7;                                                           % Number of parallel assemblies in series";
    "    end";
    "    parameters (Access = private)";
    "        T_vecK = {value(T_vecCell, 'degC') + 273.15, 'K'};";
    "    end";
    "    variables";
    "        i = {0, 'A'};                                                    % Module current";
    "        v = {0, 'V'};                                                    % Module voltage";
    "        iCell = {0, 'A'};                                                % Cell current";
    "        vCell = {0, 'V'};                                                % Cell voltage";
    "        socCell = {value = {1, '1'}, priority = priority.high};          % Cell state of charge";
    "        numCyclesCell = {value = {0, '1'}, priority = priority.high};    % Equivalent full cycles";
    "        temperatureCell = {value = {298.15, 'K'}, priority = priority.high}; % Cell temperature";
    "        vParallelAssembly = {repmat(0, S, 1), 'V'};                      % Parallel assembly voltages";
    "        socParallelAssembly = {repmat(1, S, 1), '1'};                    % Parallel assembly SOC";
    "    end";
    "    branches";
    "        i : n.i -> p.i;";
    "    end";
    "    equations";
    "        v == p.v - n.v;";
    "        iCell == i/P;";
    "        let";
    "            V0 = tablelookup(SOC_vecCell, T_vecK, V0_matCell, socCell, temperatureCell, interpolation = linear, extrapolation = extrapolation_optionCell);";
    "            R0 = tablelookup(SOC_vecCell, T_vecK, R0_matCell, socCell, temperatureCell, interpolation = linear, extrapolation = extrapolation_optionCell);";
    "        in";
    "            vCell == V0 - iCell*R0;";
    "            v == S*vCell;";
    "            socCell.der == -iCell/AHCell;";
    "            temperatureCell.der == iCell^2*R0/thermal_massCell;";
    "        end";
    "        numCyclesCell.der == abs(iCell)/(2*AHCell);";
    "        vParallelAssembly == repmat(vCell, S, 1);";
    "        socParallelAssembly == repmat(socCell, S, 1);";
    "        socOutCell == socCell;";
    "    end";
    "end";
    ""
];
writelines(L, fullfile(pkg, 'ModuleType1.ssc'));
rehash;
fprintf('Created %s\n', fullfile(pkg, 'ModuleType1.ssc'));